const express=require("express");
const cors=require("cors");
const helmet=require("helmet");
const compression=require("compression");
const cookieParser=require("cookie-parser");
const rateLimit=require("express-rate-limit");
const path=require("path");
const {notFound,errorHandler}=require("./middleware/errors");
const app=express();
app.disable("x-powered-by");
app.use(helmet({contentSecurityPolicy:false}));
app.use(compression());
app.use(cors({origin:(process.env.CLIENT_ORIGIN||"http://localhost:8080").split(",").map(x=>x.trim()),credentials:true}));
app.use(express.json({limit:"1mb"}));
app.use(cookieParser());
app.use("/api/auth",rateLimit({windowMs:15*60*1000,limit:30,standardHeaders:true,legacyHeaders:false}));
app.use("/api/orders",rateLimit({windowMs:15*60*1000,limit:12,standardHeaders:true,legacyHeaders:false}));
app.use("/api/auth",require("./routes/auth"));
app.use("/api/uploads",require("./routes/uploads"));
app.use("/api/products",require("./routes/products"));
app.use("/api/categories",require("./routes/categories"));
app.use("/api/orders",require("./routes/orders"));
app.use("/api/inventory",require("./routes/inventory"));
app.use("/api/dashboard",require("./routes/dashboard"));
app.use("/api/customers",require("./routes/customers"));
app.get("/api/health",(req,res)=>res.json({ok:true,service:"paati-and-co-api",database:"connected",paymentMethods:["cod"]}));
const storefrontPath=path.join(__dirname,"../storefront");
app.use("/admin",express.static(path.join(__dirname,"../public/admin")));
app.use(express.static(storefrontPath));
app.get("/",(req,res)=>res.sendFile(path.join(storefrontPath,"index.html")));
app.use(notFound);
app.use(errorHandler);
module.exports=app;
